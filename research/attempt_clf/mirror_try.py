"""Does training the detector on mirrored frames help? (backfill + test)    python -I research/attempt_clf/mirror_try.py --crop

1. Backfill: clips whose video is on disk but whose cached features lack mirrored ones (Xm) are re-extracted
   (the old cache is kept as .npz.bak). 2. Leave-one-fight-out frame ROC-AUC of detector v2, trained on the original
   frames only vs the original frames plus the mirrored copies of the training fights (test fights stay unmirrored).
Writes reports/mirror_try.md.
"""
import shutil
import sys
from pathlib import Path

import numpy as np

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(Path(__file__).parent))
import attempt_clf as ac  # noqa: E402


def backfill():
    per = ac.CACHE.parent / f"clips{ac.TAG}"
    clips = dict(ac.clips_and_windows())
    todo = {}
    for name, info in clips.items():
        f = per / f"{name}.npz"
        if f.exists() and "Xm" not in np.load(f).files and ac.clip_path(name).exists():
            shutil.copy2(f, f.with_suffix(".npz.bak"))
            f.unlink()
            todo[name] = info
    print("re-extracting", len(todo), "clips with mirrors", flush=True)
    if todo:
        ac._extract_new(todo, per)
    ac.extract(clips)                      # rebuild the combined cache from the per-clip files
    return per


def main():
    from sklearn.linear_model import LogisticRegression
    from sklearn.metrics import roc_auc_score

    import detector_v2 as d2
    per = backfill()
    d = np.load(ac.CACHE)
    X, y, fight, clip, t, names = d["X"], d["y"], d["fight"], d["clip"], d["t"], d["names"]
    Xm = np.full_like(X, np.nan)
    for ci, name in enumerate(names):
        c = np.load(per / f"{name}.npz")
        if "Xm" not in c.files:
            continue
        idx = np.where(clip == ci)[0]
        j = np.searchsorted(c["t"], t[idx])
        ok = (j < len(c["t"])) & (np.abs(c["t"][np.clip(j, 0, len(c["t"]) - 1)] - t[idx]) < 1e-3)
        Xm[idx[ok]] = c["Xm"][j[ok]]
    has = ~np.isnan(Xm).any(1)
    C, Cm = d2.context(X, clip), d2.context(np.where(has[:, None], Xm, X), clip)
    p0, p1 = np.full(len(y), np.nan), np.full(len(y), np.nan)
    for f in np.unique(fight):
        te = fight == f
        tr = ~te
        if y[tr].min() == y[tr].max():
            continue
        base = LogisticRegression(C=0.5, max_iter=3000, class_weight="balanced").fit(C[tr], y[tr])
        p0[te] = base.predict_proba(C[te])[:, 1]
        m = tr & has
        mir = LogisticRegression(C=0.5, max_iter=3000, class_weight="balanced").fit(np.vstack([C[tr], Cm[m]]), np.r_[y[tr], y[m]])
        p1[te] = mir.predict_proba(C[te])[:, 1]
        print(f, flush=True)
    ok = ~np.isnan(p0)
    fights_m = len(np.unique(fight[has]))
    a0, a1 = roc_auc_score(y[ok], p0[ok]), roc_auc_score(y[ok], p1[ok])
    sub = ok & has
    b0, b1 = roc_auc_score(y[sub], p0[sub]), roc_auc_score(y[sub], p1[sub])
    out = ["# Mirrored training for the attempt detector", "",
           f"Generated by `research/attempt_clf/mirror_try.py`. {has.sum()} of {len(y)} frames ({fights_m} fights) have mirrored copies; "
           "leave-one-fight-out, frame ROC-AUC, test frames never mirrored.", "",
           "| Frames scored | Original only | Plus mirrored training frames |", "|---|---|---|",
           f"| All | {a0:.3f} | {a1:.3f} |", f"| Fights with mirrors | {b0:.3f} | {b1:.3f} |", "",
           "Differences under about 0.01 are within run-to-run noise at this size (estimate)."]
    (ROOT / "reports/mirror_try.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
