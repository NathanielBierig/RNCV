"""Pilot findings: what the labels say so far, plainly (EXPLORATORY; the pre-registered test waits for ~150 attempts).

    python research/model/findings.py      -> reports/findings_pilot.md

Per factor, at the 2-s landmark: attempts, finishes, finish rate with a 95% Wilson interval. Also: seconds on the
neck before a finish, finish rate by attempt number within a round (re-attacks), and finish-list vs failure-round
counts. Bell-censored attempts are left out of the rates (PREREG §3). The sample is finish-enriched (most attempts
come from the finish list), so compare rates WITH EACH OTHER, not with the real-world finish rate.
"""
import csv
import statistics as stx
from pathlib import Path

import state_model as sm

ROOT = Path(__file__).resolve().parents[2]
SUCCESS = {"tap", "ref_stop", "unconscious"}
FACTORS = [
    ("Arm position", "choke_arm_position", [("under the chin", {"under_chin"}), ("over the jaw", {"over_jaw"})]),
    ("Grip", "rnc_style", [("figure-four", {"figure_four"}), ("palm / gable / wrist pull", {"palm_to_palm", "gable", "wrist_pull"}),
                           ("one arm / short choke", {"one_arm", "short_choke"})]),
    ("Legs", "control", [("body triangle", {"body_triangle"}), ("both hooks", {"two_hooks"}), ("one hook / none", {"one_hook", "none"})]),
    ("Defender 2-on-1", "defender_two_on_one", [("yes", {"True"}), ("no", {"False"})]),
    ("Defender flattened", "opponent_flattened", [("yes", {"True"}), ("no", {"False"})]),
    ("Choking hand hidden", "choking_hand_tucked", [("yes", {"True"}), ("no", {"False"})]),
    ("Chin tucked", "chin_tucked", [("yes", {"True"}), ("no", {"False"})]),
]


def line(label, rs):
    n, k = len(rs), sum(r["outcome"] in SUCCESS for r in rs)
    if not n:
        return f"| {label} | 0 | — | — |"
    a, b = sm.wilson(k, n)
    return f"| {label} | {n} | {k} ({100 * k / n:.0f}%) | {100 * a:.0f}–{100 * b:.0f}% |"


def main():
    rows = [r for r in csv.DictReader(open(ROOT / "phase3_labels/labels.csv", encoding="utf-8"))
            if "excluded_" not in r["notes"] and r["outcome"] != "bell"]
    fights = {r["fight_id"] for r in rows}
    out = ["# Pilot findings (exploratory)", "",
           f"{len(rows)} attempts from {len(fights)} UFC fights (bell-censored attempts left out). Generated by "
           "`research/model/findings.py`. **Exploratory:** these are descriptive rates, not the pre-registered test. "
           "The sample is finish-enriched (finish-list fights), so the overall rate is far above the real-world one; "
           "compare rows with each other. The 95% intervals are wide: overlapping intervals mean no clear difference yet.", ""]
    for title, key, groups in FACTORS:
        out += [f"## {title} (at 2 s)", "", "| Value | Attempts | Finished | 95% interval |", "|---|---|---|---|"]
        for label, vals in groups:
            out.append(line(label, [r for r in rows if sm.state_at(r, sm.LANDMARK).get(key, "") in vals]))
        out.append("")
    # re-attacks: attempt number within the round
    by = {}
    for r in rows:
        by.setdefault((r["fight_id"], r["round"]), []).append(r)
    nth = {}
    for rs in by.values():
        for i, r in enumerate(sorted(rs, key=lambda q: float(q["video_time_start"]))):
            nth[id(r)] = i + 1
    out += ["## Re-attacks (attempt number within the round)", "", "| Attempt | Attempts | Finished | 95% interval |",
            "|---|---|---|---|"]
    for label, f in (("1st", lambda n: n == 1), ("2nd", lambda n: n == 2), ("3rd or later", lambda n: n >= 3)):
        out.append(line(label, [r for r in rows if f(nth[id(r)])]))
    out += ["", "Caution: in finish-list rounds the finish is by construction the last attempt, so later attempts look "
            "more successful. Only failure rounds and random fights can test re-attacks fairly.", ""]
    # time on the neck
    fin = [sm.duration(r) for r in rows if r["outcome"] in SUCCESS]
    esc = [sm.duration(r) for r in rows if r["outcome"] not in SUCCESS]
    out += ["## Seconds on the neck", "",
            f"- Finishes: median **{stx.median(fin):.1f} s** (middle half {stx.quantiles(fin, n=4)[0]:.1f}–{stx.quantiles(fin, n=4)[2]:.1f} s), n = {len(fin)}.",
            f"- Failed attempts: median **{stx.median(esc):.1f} s** (middle half {stx.quantiles(esc, n=4)[0]:.1f}–{stx.quantiles(esc, n=4)[2]:.1f} s), n = {len(esc)}.",
            "- For comparison, lock to unconsciousness averaged 9.0 s in 81 MMA choke-outs (Stellpflug 2020).", ""]
    src = {}
    for r in rows:
        src[r["found_via"]] = src.get(r["found_via"], 0) + 1
    out += ["## Where the attempts come from", "", ", ".join(f"{k}: {v}" for k, v in sorted(src.items())),
            "", "Failure rounds and the random subset are what make these rates honest; they're the next labeling priority."]
    (ROOT / "reports/findings_pilot.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
