"""Does the HP meter match what happened? (EXPLORATORY)    python research/model/hp_check.py  -> reports/hp_check.md

HP runs consciousness_trace the way the demo does (2-s ramp-in, carry-over between attempts in a round). Compared with
the labeled outcome: when HP reaches 0 vs when the choke ended, and whether the lowest HP separates finishes from failures.
HP's constants come from physiology and judgement, not from these labels, so this is a check, not a fit.
"""
import csv
import statistics as stx
from collections import defaultdict
from pathlib import Path

import state_model as sm

ROOT = Path(__file__).resolve().parents[2]
SUCCESS = {"tap", "ref_stop", "unconscious"}
RAMP = 2.0


def traces(rows, g):
    """Per attempt: (row, trace), carrying (B, D) over a round; the gap between attempts recovers as light squeeze does."""
    by = defaultdict(list)
    for r in rows:
        by[(r["fight_id"], r["round"])].append(r)
    out = []
    for rs in by.values():
        B, D, prev_end = 0.0, 0.0, None
        for r in sorted(rs, key=lambda q: float(q["video_time_start"])):
            if prev_end is not None:
                gap = max(0.0, float(r["video_time_start"]) - prev_end)
                B *= 2.718281828 ** (-gap / g["blood_recovery_secs"])
                D *= 2.718281828 ** (-gap / g["fatigue_recovery_secs"])
            tr = sm.consciousness_trace(r, g=g, start=(B, D), ramp_in=RAMP)
            B, D = tr[-1][2], tr[-1][3]
            prev_end = float(r["video_time_end"])
            out.append((r, tr))
    return out


def auc(pos, neg):
    wins = sum((p < n) + 0.5 * (p == n) for p in pos for n in neg)   # lower HP should mean finish
    return wins / (len(pos) * len(neg))


def summary(rows, g):
    fin, fail, lead, zero_fail = [], [], [], 0
    for r, tr in traces(rows, g):
        low = min(p[1] for p in tr)
        hit = next((p[0] for p in tr if p[1] <= 0), None)
        if r["outcome"] in SUCCESS:
            fin.append(low)
            lead.append(None if hit is None else tr[-1][0] - hit)
        else:
            fail.append(low)
            zero_fail += hit is not None
    hits = [v for v in lead if v is not None]
    return {"fin": fin, "fail": fail, "reached": len(hits), "lead": stx.median(hits) if hits else float("nan"),
            "zero_fail": zero_fail, "auc": auc(fin, fail), "low_fin": stx.median(fin), "low_fail": stx.median(fail)}


def main():
    rows = [r for r in csv.DictReader(open(ROOT / "phase3_labels/labels.csv", encoding="utf-8"))
            if "excluded_" not in r["notes"] and r["outcome"] != "bell"]
    out = ["# HP meter vs what happened (exploratory)", "",
           f"{len(rows)} attempts. Generated by `research/model/hp_check.py`. HP settings come from physiology and judgement; "
           "only the top row is the setting in use, the rest show how much that choice matters.", "",
           "| Seconds to empty | Finishes reaching HP 0 | Median seconds from HP 0 to the end | Failures reaching HP 0 | Median lowest HP: finish vs failure | Lowest HP separates finish from failure (AUC) |",
           "|---|---|---|---|---|---|"]
    base = sm.CONSCIOUSNESS["secs_to_out"]
    for secs in (base, 12, 15, 20, 30):
        s = summary(rows, {**sm.CONSCIOUSNESS, "secs_to_out": secs})
        out.append(f"| {secs:g} | {s['reached']}/{len(s['fin'])} | {s['lead']:.1f} | {s['zero_fail']}/{len(s['fail'])} | "
                   f"{s['low_fin']:.0f} vs {s['low_fail']:.0f} | {s['auc']:.2f} |")
    s = summary(rows, sm.CONSCIOUSNESS)
    q1, q2, a = s["auc"] / (2 - s["auc"]), 2 * s["auc"] ** 2 / (1 + s["auc"]), s["auc"]
    n1, n2 = len(s["fin"]), len(s["fail"])
    se = ((a * (1 - a) + (n1 - 1) * (q1 - a * a) + (n2 - 1) * (q2 - a * a)) / (n1 * n2)) ** 0.5     # Hanley-McNeil
    out += ["", f"**How to read it:** most finishes end before HP reaches 0, because a fighter usually taps while still "
            f"conscious, so HP 0 is not a forecast of the tap. Some failures reach HP 0, so the meter can overstate the danger. "
            f"The lowest HP separates finishes from failures only weakly: AUC {a:.2f}, about {a - 1.96 * se:.2f}-{a + 1.96 * se:.2f}, "
            "a range that touches chance (0.50). It is also partly about time, since longer attempts drain more HP. "
            "HP is a readable estimate for viewers, not a validated measure, and the setting stays at the published 9 s."]
    (ROOT / "reports/hp_check.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
