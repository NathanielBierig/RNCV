"""Are some choke grips better than others? (EXPLORATORY on these attempts, H4 of PREREG A7)
    python research/model/grip_hierarchy.py  -> reports/grip_hierarchy.md

Grip at the 2-s landmark, ranked in advance from coaching: figure-four (2), a two-handed lock without the biceps anchor (1:
palm-to-palm, gable, wrist pull), no real lock (0: one arm, short choke). Firth logistic with the rank as one number and
the arm position held fixed: a multiplier above 1 means each step up the ladder raises the odds. The attempts in this
report helped suggest H4, so they can't confirm it; only attempts labeled after 2026-11-01 can.
"""
import csv
import math
import sys
from pathlib import Path

import numpy as np

import state_model as sm

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT / "research/rnc_science"))
import prereg_analysis as pa  # noqa: E402

SUCCESS = {"tap", "ref_stop", "unconscious"}
RANK = {"figure_four": 2, "palm_to_palm": 1, "gable": 1, "wrist_pull": 1, "one_arm": 0, "short_choke": 0}
NAMES = {"figure_four": "Figure-four", "palm_to_palm": "Palm-to-palm", "gable": "Gable", "wrist_pull": "Wrist pull",
         "short_choke": "Short choke", "one_arm": "One arm"}


def trend(rows, split=None):
    """Multiplier per rank step, or for `split` a figure-four vs other two-handed locks contrast among two-handed locks."""
    X, y = [], []
    for r in rows:
        st = sm.state_at(r, sm.LANDMARK)
        g, arm = st.get("rnc_style", ""), {"under_chin": 1.0, "over_jaw": 0.0}.get(st.get("choke_arm_position", ""))
        if g not in RANK or arm is None or (split and RANK[g] == 0):
            continue
        X.append([1.0, arm, float(g == "figure_four") if split else RANK[g]])
        y.append(float(r["outcome"] in SUCCESS))
    X, y = np.array(X), np.array(y)
    beta, pl = pa.firth(X, y)
    lo, hi = pa.profile_ci(X, y, 2, beta, pl)
    return f"x{math.exp(beta[2]):.2f} ({math.exp(lo):.2f}-{math.exp(hi):.2f}), n = {len(y)}"


def main():
    rows = [r for r in csv.DictReader(open(ROOT / "phase3_labels/labels.csv", encoding="utf-8"))
            if "excluded_" not in r["notes"] and r["outcome"] != "bell"]
    out = ["# Grip hierarchy (exploratory)", "", "Generated by `research/model/grip_hierarchy.py`. Finish-enriched sample: compare rows with each other.", "",
           "| Grip at 2 s | Attempts | Finished | 95% interval |", "|---|---|---|---|"]
    for g, name in NAMES.items():
        sub = [r for r in rows if sm.state_at(r, sm.LANDMARK).get("rnc_style", "") == g]
        k = sum(r["outcome"] in SUCCESS for r in sub)
        if sub:
            a, b = sm.wilson(k, len(sub))
            out.append(f"| {name} | {len(sub)} | {k} ({100 * k / len(sub):.0f}%) | {100 * a:.0f}–{100 * b:.0f}% |")
    rounds = {}
    for r in sorted(rows, key=lambda q: float(q["video_time_start"])):
        rounds.setdefault((r["fight_id"], r["round"]), []).append(r)
    first = [rs[0] for rs in rounds.values()]
    out += ["", f"Each step up the ladder, arm position held fixed: **{trend(rows)}**.",
            f"First attempt in each round only: **{trend(first)}**.",
            f"Figure-four vs other two-handed locks, arm position held fixed: **{trend(rows, split=True)}**.", "",
            "**How to read it:** attempts in one round aren't independent. A round can end only once, so every earlier attempt "
            "in a finish round failed, and attackers had usually improved their grip by the last attempt. Part of the all-attempts "
            "trend may come from that order. The first attempt in each round avoids it, and there the range includes no effect. "
            "Only 1 palm-to-palm and 0 gables were seen, so the ladder is mostly figure-four against everything else."]
    (ROOT / "reports/grip_hierarchy.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
