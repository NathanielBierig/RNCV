"""Does a choke get more dangerous the longer it stays on? (EXPLORATORY)
    python research/model/time_curve.py  -> reports/time_curve.md, docs/media/time_on_neck.png

For each 5-s block on the neck: of the attempts still going when it began, how many finished and how many ended
without a finish during it. The sample is finish-enriched, so compare blocks with each other, not with the real world.
"""
import csv
from pathlib import Path

import state_model as sm

ROOT = Path(__file__).resolve().parents[2]
SUCCESS = {"tap", "ref_stop", "unconscious"}
EDGES = [0, 5, 10, 15, 20]


def blocks(rows):
    out = []
    for lo, hi in zip(EDGES, EDGES[1:] + [1e9]):
        alive = [r for r in rows if sm.duration(r) >= lo]
        ended = [r for r in alive if sm.duration(r) < hi]
        fin = sum(r["outcome"] in SUCCESS for r in ended)
        out.append({"lo": lo, "hi": hi, "alive": len(alive), "fin": fin, "fail": len(ended) - fin})
    return out


def grip(r):
    st = sm.state_at(r, sm.LANDMARK).get("rnc_style", "")
    return "figure-four" if st == "figure_four" else "any other grip"


def chart(bl):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    labels = [f"{b['lo']}-{b['hi']} s" if b["hi"] < 1e9 else f"{b['lo']}+ s" for b in bl]
    rates = [100 * b["fin"] / b["alive"] for b in bl]
    ci = [[100 * v for v in sm.wilson(b["fin"], b["alive"])] for b in bl]
    fig, ax = plt.subplots(figsize=(6.4, 3.2), dpi=150)
    ax.bar(labels, rates, color="#d97706")
    ax.errorbar(labels, rates, yerr=[[r - c[0] for r, c in zip(rates, ci)], [c[1] - r for r, c in zip(rates, ci)]],
                fmt="none", ecolor="#1c2128", capsize=4, lw=1)
    for x, b in enumerate(bl):
        ax.text(x, 2, f"n={b['alive']}", ha="center", fontsize=8, color="white")
    ax.set_ylabel("Finished in this block (%)")
    ax.set_xlabel("Seconds on the neck")
    ax.set_ylim(0, 100)
    ax.spines[["top", "right"]].set_visible(False)
    fig.tight_layout()
    fig.savefig(ROOT / "docs/media/time_on_neck.png")


def table(bl):
    out = ["| Seconds on the neck | Still going at the start | Finished in this block | Share finished (95% range) | Ended without a finish |", "|---|---|---|---|---|"]
    for b in bl:
        lo, hi = sm.wilson(b["fin"], b["alive"])
        name = f"{b['lo']}-{b['hi']}" if b["hi"] < 1e9 else f"{b['lo']}+"
        out.append(f"| {name} | {b['alive']} | {b['fin']} | {100 * b['fin'] / b['alive']:.0f}% ({100 * lo:.0f}–{100 * hi:.0f}%) | {b['fail']} |")
    return out


def main():
    rows = [r for r in csv.DictReader(open(ROOT / "phase3_labels/labels.csv", encoding="utf-8"))
            if "excluded_" not in r["notes"] and r["outcome"] != "bell"]
    bl = blocks(rows)
    chart(bl)
    out = ["# Time on the neck (exploratory)", "", f"{len(rows)} attempts. Generated by `research/model/time_curve.py`. "
           "Finish-enriched sample: compare blocks with each other, not with the real world.", ""] + table(bl)
    for g in ("figure-four", "any other grip"):
        sub = [r for r in rows if grip(r) == g]
        out += ["", f"## {g} at 2 s ({len(sub)} attempts)", ""] + table(blocks(sub))
    out += ["", "**How to read it:** the first 5 s rarely end in a finish. After that the share per block stays roughly flat, "
            "so more time on the neck doesn't keep raising the danger the way a time ramp would. The 20+ row has no upper "
            "limit, so it isn't comparable with the 5-s rows. Small numbers: overlapping ranges are not differences."]
    (ROOT / "reports/time_curve.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
