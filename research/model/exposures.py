"""Whole back exposures (EXPLORATORY): does leg control buy retention and re-attacks rather than single finishes?

    python research/model/exposures.py      -> reports/back_exposures.md

A back exposure = a run of attempts in the same round on the same back take: a new exposure starts after an
`escape` (the defender got out and the attacker lost the back) or after more than GAP seconds without an attempt.
Per exposure: leg control at its first attempt's 2-s landmark, number of attempts, span from the first start to the
last end, total seconds with the arm on the neck, and whether ANY attempt finished.
Caveats: only labeled attempts are seen (time on the back with no choke attempt isn't labeled), and finish-list
rounds always contain a finish, so compare groups with each other, not with the real world.
"""
import csv
import statistics as stx
from collections import defaultdict
from pathlib import Path

import state_model as sm

ROOT = Path(__file__).resolve().parents[2]
SUCCESS = {"tap", "ref_stop", "unconscious"}
GAP = 30.0
LEGS = {"body_triangle": "body triangle", "two_hooks": "both hooks", "one_hook": "one hook / none", "none": "one hook / none"}


def exposures(rows):
    by = defaultdict(list)
    for r in rows:
        by[(r["fight_id"], r["round"])].append(r)
    out = []
    for rs in by.values():
        cur = []
        for r in sorted(rs, key=lambda q: float(q["video_time_start"])):
            if cur and (cur[-1]["outcome"] == "escape" or
                        float(r["video_time_start"]) - float(cur[-1]["video_time_end"]) > GAP):
                out.append(cur); cur = []
            cur.append(r)
        out.append(cur)
    return out


def summary(ex):
    first = ex[0]
    return {"legs": LEGS.get(sm.state_at(first, sm.LANDMARK).get("control", ""), "unclear"),
            "n": len(ex), "finished": any(r["outcome"] in SUCCESS for r in ex),
            "span": float(ex[-1]["video_time_end"]) - float(first["video_time_start"]),
            "neck": sum(sm.duration(r) for r in ex), "via": first["found_via"]}


def main():
    rows = [r for r in csv.DictReader(open(ROOT / "phase3_labels/labels.csv", encoding="utf-8"))
            if "excluded_" not in r["notes"] and r["outcome"] != "bell"]
    ex = [summary(e) for e in exposures(rows)]
    out = ["# Whole back exposures (exploratory)", "",
           f"{len(rows)} attempts grouped into **{len(ex)} back exposures** (a new exposure starts after an escape or "
           f"{GAP:.0f} s without an attempt). Generated by `research/model/exposures.py`. Exploratory: small numbers, "
           "finish-enriched sample, and time on the back without a choke attempt isn't labeled.", "",
           "| Leg control at the first attempt | Exposures | Finished (any attempt) | 95% interval | Attempts per exposure (mean) | Seconds on the neck per exposure (median) | Exposure span, s (median) |",
           "|---|---|---|---|---|---|---|"]
    for g in ("body triangle", "both hooks", "one hook / none", "unclear"):
        e = [x for x in ex if x["legs"] == g]
        if not e:
            continue
        k = sum(x["finished"] for x in e)
        a, b = sm.wilson(k, len(e))
        out.append(f"| {g} | {len(e)} | {k} ({100 * k / len(e):.0f}%) | {100 * a:.0f}–{100 * b:.0f}% | "
                   f"{stx.mean(x['n'] for x in e):.1f} | {stx.median(x['neck'] for x in e):.1f} | {stx.median(x['span'] for x in e):.1f} |")
    multi = [x for x in ex if x["n"] > 1]
    out += ["", f"Exposures with more than one attempt: **{len(multi)} of {len(ex)}**. Finish rate when the attacker got "
            f"2+ attempts: {sum(x['finished'] for x in multi)}/{len(multi)}; with a single attempt: "
            f"{sum(x['finished'] for x in ex if x['n'] == 1)}/{sum(1 for x in ex if x['n'] == 1)}.", "",
            "**How to read it:** if leg control buys retention, body-triangle and both-hooks exposures should show "
            "*more attempts* and *more seconds on the neck* per exposure, and their exposure-level finish rate should "
            "catch up with or pass the one-hook/none group, even though their per-attempt rate is lower "
            "([findings_pilot.md](findings_pilot.md)). With this few exposures, differences within the 95% intervals "
            "are not evidence either way."]
    (ROOT / "reports/back_exposures.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
